#!/usr/bin/env python3
"""Resolve every tag in deploy/images.lock.yaml to its digest.

Writes the digests back into the lock file and writes deploy/images.env with one
``IMG_<NAME>=<image>@sha256:...`` line per image, which Compose reads via --env-file.
Needs Docker with buildx (``docker buildx imagetools inspect``) and PyYAML.
Images built locally (SPOTBUGS_FSB) are skipped with a note until they exist in a registry.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "deploy" / "images.lock.yaml"
ENV = ROOT / "deploy" / "images.env"
LOCAL_BUILT = {"SPOTBUGS_FSB"}
DIGEST_RE = re.compile(r"^Digest:\s+(sha256:[0-9a-f]{64})\s*$", re.MULTILINE)


def resolve(image: str, tag: str) -> str:
    out = subprocess.run(
        ["docker", "buildx", "imagetools", "inspect", f"{image}:{tag}"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    match = DIGEST_RE.search(out)
    if not match:
        raise RuntimeError(f"no digest in output for {image}:{tag}")
    return match.group(1)


def main() -> int:
    data = yaml.safe_load(LOCK.read_text(encoding="utf-8"))
    failures: list[str] = []
    lines: list[str] = []
    for entry in data["images"]:
        name, image, tag = entry["name"], entry["image"], entry["tag"]
        if name in LOCAL_BUILT and not entry.get("digest"):
            print(f"skip {name}: built locally")
            lines.append(f"IMG_{name}={image}:{tag}")
            continue
        try:
            entry["digest"] = resolve(image, tag)
            print(f"ok   {name}: {image}:{tag} -> {entry['digest']}")
        except (subprocess.CalledProcessError, RuntimeError, FileNotFoundError) as exc:
            failures.append(f"{name} ({image}:{tag}): {exc}")
            continue
        lines.append(f"IMG_{name}={image}@{entry['digest']}")
    if failures:
        print("\nFAILED:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1
    LOCK.write_text(
        "# Generated by scripts/pin_images.py - edit tags, then re-run pin-images.\n"
        + yaml.safe_dump(data, sort_keys=False, width=120),
        encoding="utf-8",
    )
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {LOCK.relative_to(ROOT)} and {ENV.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
