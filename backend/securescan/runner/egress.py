"""The shared on-demand egress proxy (one squid container) for the worker's own outbound calls.

GitHub API calls, clones and the updaters reach the internet only through this proxy, and only to the
hosts some caller asked for. The container (``securescan-egress``, networks ``egress`` + ``backend``)
is started when the first caller needs it and stopped after ``egress_idle_minutes`` without use
(``egress_idle_stop`` periodic task, see ``securescan/jobs/egress_lifecycle.py``).

The socket proxy does not allow ``exec``, so ``squid -k reconfigure`` is not available. When the
allowlist must grow the container is removed and created again with the new configuration; the
allowlist of a running proxy therefore only ever grows until it is stopped. All changes are serialised
by one lock. Per-job DAST proxies are a different thing (M9) and do not use this module.

Usage::

    async with egress_lease({"api.github.com", "github.com"}) as proxy_url:
        ...  # use proxy_url (an empty string means "connect directly": egress disabled in dev)
"""

from __future__ import annotations

import asyncio
import hashlib
import os
import re
import time
from collections.abc import AsyncIterator, Awaitable, Callable, Iterable
from contextlib import AbstractAsyncContextManager, asynccontextmanager
from pathlib import Path
from typing import Any

from securescan.config import Settings, get_settings
from securescan.logging import get_logger
from securescan.observability.metrics import EGRESS_PROXY_UP

log = get_logger(__name__)

EGRESS_NAME = "securescan-egress"
EGRESS_PORT = 3128
LABEL_ROLE = "securescan.role"
LABEL_HOSTS = "securescan.egress.hosts"
LABEL_HASH = "securescan.egress.hash"
ROLE_VALUE = "egress"
SQUID_UID = "13:13"  # the ``proxy`` user of the Ubuntu squid image
READY_TIMEOUT_SECONDS = 30.0
LAST_USED_WRITE_INTERVAL = 30.0

_HOST_RE = re.compile(r"^[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?$")


class EgressError(Exception):
    """The egress proxy could not be started or configured (message is plain language)."""


Probe = Callable[[str, int], Awaitable[bool]]


def normalise_hosts(hosts: Iterable[str]) -> list[str]:
    """Lower-case, de-duplicate and validate host names (no wildcards, ports, schemes or spaces)."""
    result: set[str] = set()
    for raw in hosts:
        host = raw.strip().lower().rstrip(".")
        if not host:
            continue
        if not _HOST_RE.match(host) or ".." in host:
            raise EgressError("'%s' is not a valid host name for the egress allowlist." % raw[:80])
        result.add(host)
    return sorted(result)


def allow_hash(hosts: Iterable[str]) -> str:
    return hashlib.sha256("\n".join(sorted(hosts)).encode("ascii")).hexdigest()[:16]


def render_squid_conf(hosts: Iterable[str], *, port: int = EGRESS_PORT) -> str:
    """The squid configuration: CONNECT to port 443 and plain requests only for the listed hosts."""
    listed = normalise_hosts(hosts)
    if not listed:
        raise EgressError("The egress allowlist is empty.")
    lines = [
        "# Generated by SecureScan. Do not edit: it is replaced when the allowlist changes.",
        "http_port %d" % port,
        "visible_hostname %s" % EGRESS_NAME,
        "acl allowed_hosts dstdomain %s" % " ".join(listed),
        "acl SSL_ports port 443",
        "acl Safe_ports port 80 443",
        "acl CONNECT method CONNECT",
        "http_access deny !Safe_ports",
        "http_access deny CONNECT !SSL_ports",
        "http_access allow allowed_hosts",
        "http_access deny all",
        "cache deny all",
        "access_log none",
        "cache_log /var/log/squid/cache.log",
        "debug_options ALL,1",
        "pid_filename none",
        "coredump_dir /tmp",
        "forwarded_for delete",
        "via off",
        "dns_v4_first on",
        "shutdown_lifetime 3 seconds",
        "",
    ]
    return "\n".join(lines)


def _labels_of(info: dict[str, Any]) -> dict[str, str]:
    labels = (info.get("Config") or {}).get("Labels") or {}
    return {str(k): str(v) for k, v in labels.items()}


def _is_running(info: dict[str, Any] | None) -> bool:
    return bool(info and (info.get("State") or {}).get("Running"))


async def _tcp_probe(host: str, port: int) -> bool:
    try:
        _reader, writer = await asyncio.wait_for(asyncio.open_connection(host, port), timeout=2.0)
    except (OSError, asyncio.TimeoutError):
        return False
    writer.close()
    try:
        await writer.wait_closed()
    except OSError:  # pragma: no cover - the peer closed first
        pass
    return True


class EgressManager:
    """Starts, reconfigures, leases and stops the shared egress proxy. One instance per worker."""

    def __init__(
        self,
        *,
        launcher_factory: Callable[[], Any] | None = None,
        settings: Settings | None = None,
        clock: Callable[[], float] = time.time,
        sleep: Callable[[float], Awaitable[None]] = asyncio.sleep,
        probe: Probe = _tcp_probe,
        image_resolver: Callable[[], Awaitable[str]] | None = None,
    ) -> None:
        self._launcher_factory = launcher_factory
        self._settings = settings
        self._clock = clock
        self._sleep = sleep
        self._probe = probe
        self._image_resolver = image_resolver
        self._lock = asyncio.Lock()
        self._leases = 0
        self._last_used: float | None = None
        self._last_written = 0.0

    # -- plumbing ----------------------------------------------------------------------------------
    @property
    def settings(self) -> Settings:
        return self._settings or get_settings()

    def _launcher(self) -> Any:
        if self._launcher_factory is not None:
            return self._launcher_factory()
        from securescan.runner.launcher import get_launcher

        return get_launcher()

    @property
    def state_dir(self) -> Path:
        return Path(self.settings.data_root) / "egress"

    @property
    def proxy_url(self) -> str:
        return self.settings.egress_proxy_url or "http://%s:%d" % (EGRESS_NAME, EGRESS_PORT)

    async def _image(self) -> str:
        if self._image_resolver is not None:
            image = await self._image_resolver()
        else:
            image = await resolve_egress_image(self.settings)
        return image

    # -- last-used bookkeeping (shared through the data volume) ----------------------------------------
    def _touch(self, *, force: bool = False) -> None:
        now = self._clock()
        self._last_used = now
        if not force and now - self._last_written < LAST_USED_WRITE_INTERVAL:
            return
        self._last_written = now
        try:
            self.state_dir.mkdir(parents=True, exist_ok=True)
            (self.state_dir / "last_used").write_text(str(now), encoding="ascii")
        except OSError as exc:
            log.warning("egress_state_write_failed", error=type(exc).__name__)

    def _read_last_used(self) -> float | None:
        if self._last_used is not None:
            return self._last_used
        try:
            return float((self.state_dir / "last_used").read_text(encoding="ascii").strip())
        except (OSError, ValueError):
            return None

    def _write_config(self, hosts: list[str]) -> Path:
        directory = self.state_dir
        directory.mkdir(parents=True, exist_ok=True)
        os.chmod(directory, 0o755)
        path = directory / ("squid-%s.conf" % allow_hash(hosts))
        temporary = path.with_suffix(".tmp")
        temporary.write_text(render_squid_conf(hosts), encoding="ascii")
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
        for old in directory.glob("squid-*.conf"):
            if old != path:
                try:
                    old.unlink()
                except OSError:  # pragma: no cover
                    pass
        return path

    def _spec(self, image: str, hosts: list[str], config_path: Path) -> Any:
        from securescan.runner.specs import ContainerSpec

        settings = self.settings
        return ContainerSpec(
            image=image,
            name=EGRESS_NAME,
            user=SQUID_UID,
            entrypoint=["/usr/sbin/squid"],
            command=["-N", "-f", "/etc/squid/securescan.conf"],
            binds=[(str(config_path), "/etc/squid/securescan.conf", True)],
            tmpfs={
                "/tmp": "size=16m,mode=1777",  # noqa: S108 - container-internal tmpfs
                "/var/log/squid": "size=16m,uid=13,gid=13,mode=0755",
            },
            network=settings.network_backend,
            extra_networks=[settings.network_egress],
            labels={
                LABEL_ROLE: ROLE_VALUE,
                LABEL_HOSTS: ",".join(hosts),
                LABEL_HASH: allow_hash(hosts),
            },
            mem_limit="512m",
            nano_cpus=1_000_000_000,
            pids_limit=256,
            read_only_rootfs=True,
            stop_timeout=10,
        )

    # -- the proxy ---------------------------------------------------------------------------------
    async def ensure(self, hosts: Iterable[str]) -> str:
        """Make sure the proxy runs and allows ``hosts``; returns the proxy URL ("" = connect directly)."""
        settings = self.settings
        if not settings.egress_enabled:
            return ""
        wanted = set(normalise_hosts(hosts))
        if not wanted:
            raise EgressError("No hosts were requested for the egress proxy.")
        async with self._lock:
            launcher = self._launcher()
            info = await launcher.inspect(EGRESS_NAME)
            running = _is_running(info)
            current: set[str] = set()
            if info is not None and running:
                current = {h for h in _labels_of(info).get(LABEL_HOSTS, "").split(",") if h}
                if wanted <= current:
                    self._touch()
                    EGRESS_PROXY_UP.set(1)
                    return self.proxy_url
            desired = sorted(current | wanted)
            if info is not None:
                log.info(
                    "egress_recreate",
                    reason="allowlist_changed" if running else "not_running",
                    hosts=desired,
                )
                await launcher.remove(str(info.get("Id") or EGRESS_NAME), force=True)
            else:
                log.info("egress_start", hosts=desired)
            await self._start(launcher, desired)
            self._touch(force=True)
            EGRESS_PROXY_UP.set(1)
            return self.proxy_url

    async def _start(self, launcher: Any, hosts: list[str]) -> None:
        image = await self._image()
        config_path = self._write_config(hosts)
        spec = self._spec(image, hosts, config_path)
        container_id = await launcher.create(spec)
        try:
            await launcher.start(container_id)
            await self._wait_ready()
        except BaseException:
            try:
                await launcher.remove(container_id, force=True)
            except Exception as exc:  # noqa: BLE001 - the original error matters more
                log.warning("egress_cleanup_failed", error=type(exc).__name__)
            raise

    async def _wait_ready(self) -> None:
        deadline = self._clock() + READY_TIMEOUT_SECONDS
        while True:
            if await self._probe(EGRESS_NAME, EGRESS_PORT):
                return
            if self._clock() >= deadline:
                raise EgressError(
                    "The egress proxy did not become ready in %d seconds. "
                    "Check that the 'egress' and 'backend' networks exist and the squid image can start."
                    % int(READY_TIMEOUT_SECONDS)
                )
            await self._sleep(0.5)

    @asynccontextmanager
    async def lease(self, hosts: Iterable[str]) -> AsyncIterator[str]:
        """Hold the proxy open (it is never idle-stopped while a lease exists)."""
        self._leases += 1
        try:
            url = await self.ensure(hosts)
            yield url
        finally:
            self._leases -= 1
            self._touch(force=True)

    @property
    def active_leases(self) -> int:
        return self._leases

    async def stop_if_idle(self) -> bool:
        """Stop and remove the proxy when nobody used it for ``egress_idle_minutes``. True if stopped."""
        if not self.settings.egress_enabled:
            return False
        async with self._lock:
            launcher = self._launcher()
            info = await launcher.inspect(EGRESS_NAME)
            if not _is_running(info):
                EGRESS_PROXY_UP.set(0)
                return False
            if self._leases > 0:
                return False
            last_used = self._read_last_used()
            now = self._clock()
            if last_used is None:
                self._touch(force=True)  # unknown: start the idle period now
                return False
            idle_seconds = now - last_used
            if idle_seconds < self.settings.egress_idle_minutes * 60:
                return False
            assert info is not None  # noqa: S101 - _is_running said so
            container_id = str(info.get("Id") or EGRESS_NAME)
            log.info("egress_idle_stop", idle_seconds=int(idle_seconds))
            await launcher.stop(container_id, timeout=10)
            await launcher.remove(container_id, force=True)
            EGRESS_PROXY_UP.set(0)
            return True

    async def stop(self) -> None:
        """Stop and remove the proxy now (shutdown, tests)."""
        async with self._lock:
            launcher = self._launcher()
            info = await launcher.inspect(EGRESS_NAME)
            if info is not None:
                await launcher.remove(str(info.get("Id") or EGRESS_NAME), force=True)
            EGRESS_PROXY_UP.set(0)

    async def reconcile(self) -> bool:
        """Set the metric from the real container state (worker start-up). True when it is running."""
        if not self.settings.egress_enabled:
            EGRESS_PROXY_UP.set(0)
            return False
        info = await self._launcher().inspect(EGRESS_NAME)
        running = _is_running(info)
        EGRESS_PROXY_UP.set(1 if running else 0)
        if running and self._read_last_used() is None:
            self._touch(force=True)
        return running


async def resolve_egress_image(settings: Settings) -> str:
    """The squid image reference: ``SECURESCAN_EGRESS_IMAGE``, else the active ``squid`` image_versions row.

    Outside dev the reference must be pinned by digest (``@sha256:``).
    """
    reference = settings.egress_image.strip()
    if not reference:
        from sqlalchemy import select

        from securescan.db.models.images import ImageVersion
        from securescan.db.session import session_scope

        async with session_scope() as session:
            row = await session.scalar(
                select(ImageVersion)
                .where(ImageVersion.tool == "squid", ImageVersion.active.is_(True))
                .order_by(ImageVersion.created_at.desc())
                .limit(1)
            )
        if row is not None:
            reference = "%s@%s" % (row.image, row.digest)
    if not reference:
        raise EgressError(
            "The egress proxy image is not configured. Set SECURESCAN_EGRESS_IMAGE to the pinned "
            "squid image (see deploy/images.lock.yaml)."
        )
    if "@sha256:" not in reference and not settings.is_dev:
        raise EgressError("The egress proxy image must be pinned by digest (name@sha256:...).")
    return reference


# --------------------------------------------------------------------------- module-level access

_manager: EgressManager | None = None


def get_egress_manager() -> EgressManager:
    global _manager  # noqa: PLW0603 - one manager per worker process
    if _manager is None:
        _manager = EgressManager()
    return _manager


def reset_egress_manager() -> None:
    """Forget the cached manager (tests)."""
    global _manager  # noqa: PLW0603
    _manager = None


async def ensure_egress(hosts: set[str]) -> str:
    """Start the shared proxy if needed, make sure it allows ``hosts`` and return its URL.

    An empty string means egress is disabled (dev): connect directly. Prefer ``egress_lease`` for work
    that takes a while, so the proxy is not idle-stopped underneath it.
    """
    return await get_egress_manager().ensure(hosts)


def egress_lease(hosts: Iterable[str]) -> AbstractAsyncContextManager[str]:
    """``async with egress_lease(hosts) as proxy_url:`` keeps the proxy alive for the block."""
    return get_egress_manager().lease(hosts)


async def egress_idle_stop() -> bool:
    """Stop the shared proxy when it has been idle long enough (the periodic task calls this)."""
    return await get_egress_manager().stop_if_idle()
